import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
import textfeatures as tf  # noqa: E402


def sentences(text):
    norm = tf.normalize(text)
    return [norm[a:b] for a, b in tf.sentence_spans(norm)]


class SentenceSplitTest(unittest.TestCase):
    def test_basic_punctuation(self):
        self.assertEqual(sentences("One. Two? Three!"), ["One.", "Two?", "Three!"])

    def test_closing_quote_after_period(self):
        self.assertEqual(sentences('He said "it works." Then he left.'), ['He said "it works."', "Then he left."])

    def test_abbreviations_and_initials(self):
        text = "Dr. Smith et al. (2020) studied the U.S. market. J. K. Rowling agreed, e.g. in interviews. Done."
        self.assertEqual(sentences(text), [
            "Dr. Smith et al. (2020) studied the U.S. market.",
            "J. K. Rowling agreed, e.g. in interviews.",
            "Done.",
        ])

    def test_decimal_is_not_a_boundary(self):
        self.assertEqual(sentences("The rate was 3.5 percent. It rose."), ["The rate was 3.5 percent.", "It rose."])

    def test_paragraph_break_ends_heading(self):
        self.assertEqual(sentences("Introduction\n\nOnline classes grew."), ["Introduction", "Online classes grew."])


class NormalizeTest(unittest.TestCase):
    def test_length_is_preserved(self):
        for text in ["a\r\nb", "it’s fine\n\nnext", "line one\nline two\nline three"]:
            self.assertEqual(len(tf.normalize(text)), len(text))

    def test_hard_wrapped_lines_are_joined(self):
        text = ("The recent advancements in artificial intelligence combined with the\n"
                "extensive amount of data generated by clinical systems has led to the\n"
                "development of imaging solutions.")
        self.assertNotIn("\n", tf.normalize(text))
        self.assertEqual(len(tf.paragraphs(tf.normalize(text))), 1)

    def test_word_paste_keeps_one_paragraph_per_line(self):
        text = "Introduction\nOnline learning has grown quickly.\nMany students like it.\nMethods\nWe surveyed students."
        self.assertEqual(len(tf.paragraphs(tf.normalize(text))), 5)

    def test_curly_apostrophes(self):
        self.assertEqual(tf.words(tf.normalize("I don’t know")), ["i", "don't", "know"])


class MeasureTest(unittest.TestCase):
    def test_mattr(self):
        self.assertIsNone(tf.mattr([]))
        self.assertEqual(tf.mattr(["a", "b", "a", "c"]), 0.75)
        self.assertAlmostEqual(tf.mattr(("the cat sat on the mat " * 30).split()), 0.1)
        self.assertEqual(tf.mattr([f"w{i}" for i in range(120)]), 1.0)

    def test_phrase_hits_do_not_overlap(self):
        hits = tf.phrase_hits("it is important to note it is important".split(), ["it is important", "important to note"])
        self.assertEqual(hits, [("it is important", 0, 3), ("it is important", 5, 8), ("important to note", 2, 5)])

    def test_analyze_reports_hit_positions_in_text(self):
        text = "Moreover, it works. It is important to note this."
        result = tf.analyze(text, ["moreover", "it is important to note"])
        hits = [h for s in result["sentence_details"] for h in s["hits"]]
        self.assertEqual([text[a:b] for _, a, b in hits], ["Moreover", "It is important to note"])
        self.assertEqual(result["sentences"], 2)

    def test_empty_text(self):
        result = tf.analyze("   ", ["moreover"])
        self.assertEqual(result["words"], 0)
        self.assertEqual(result["sentence_details"], [])


if __name__ == "__main__":
    unittest.main()
