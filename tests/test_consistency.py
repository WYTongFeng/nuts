"""网页用的 nuts-core.js 和 Python 的 textfeatures.py / model.py 必须算出一样的结果。需要 node。"""
import json
import math
import shutil
import subprocess
import sys
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
import model as nm  # noqa: E402
import textfeatures as tf  # noqa: E402

PHRASES = ["moreover", "furthermore", "it is important to note", "plays a crucial role", "in conclusion",
           "additionally", "overall"]

TEXTS = [
    (ROOT / "samples" / "casual.txt").read_text(encoding="utf-8"),
    (ROOT / "samples" / "ai-style.txt").read_text(encoding="utf-8"),
    'He said "it works." Then he left. Did it? Yes!',
    "Dr. Smith et al. (2020) studied the U.S. market. J. K. Rowling agreed, e.g. in interviews.",
    "Introduction\nOnline learning has grown quickly.\nMany students like it.\nMethods\nWe surveyed 40 students.",
    "The recent advancements in artificial intelligence combined with the\nextensive amount of data generated by\n"
    "clinical systems has led to new tools.\n\nAdditionally, it is important to note the costs.",
    "I don’t think it’s ‘fine’... Really?! Overall, moreover, furthermore.",
    "  \n\n  Leading and trailing space.  \n\n",
    "word " * 120,
    "",
]

NODE_SCRIPT = """
const core = require(process.argv[1]);
const input = JSON.parse(require("fs").readFileSync(0, "utf8"));
const out = input.texts.map((t) => {
  const norm = core.normalize(t);
  const analysis = core.analyze(t, input.phrases);
  const values = core.docValues(analysis, null);
  return {
    norm,
    spans: core.sentenceSpans(norm),
    analysis,
    prob: input.model ? core.probability(input.model.doc.rules, values) : null,
    sentenceProbs: input.model ? analysis.sentence_details.map(
      (s) => core.probability(input.model.sentence.rules, core.sentenceValues(s, null))) : [],
  };
});
process.stdout.write(JSON.stringify(out));
"""


def close(a, b):
    if isinstance(a, float) or isinstance(b, float):
        return a is not None and b is not None and math.isclose(a, b, rel_tol=1e-9, abs_tol=1e-12)
    return a == b


@unittest.skipUnless(shutil.which("node"), "需要 node 才能运行 JS")
class ConsistencyTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        model_path = ROOT / "model.json"
        cls.model = nm.load(model_path) if model_path.exists() else None
        result = subprocess.run(
            ["node", "-e", NODE_SCRIPT, str(ROOT / "nuts-core.js")],
            input=json.dumps({"texts": TEXTS, "phrases": PHRASES, "model": cls.model}),
            capture_output=True, text=True, check=True)
        cls.js = json.loads(result.stdout)

    def test_normalize_and_spans(self):
        for text, js in zip(TEXTS, self.js):
            norm = tf.normalize(text)
            self.assertEqual(js["norm"], norm)
            self.assertEqual([tuple(s) for s in js["spans"]], tf.sentence_spans(norm))

    def test_features(self):
        for text, js in zip(TEXTS, self.js):
            py = tf.analyze(text, PHRASES)
            for key, value in py.items():
                if key == "sentence_details":
                    continue
                self.assertTrue(close(value, js["analysis"][key]), f"{key}: {value} != {js['analysis'][key]} ({text[:30]!r})")
            for ps, js_s in zip(py["sentence_details"], js["analysis"]["sentence_details"], strict=True):
                for key in ("start", "end", "words", "commas"):
                    self.assertEqual(ps[key], js_s[key])
                self.assertTrue(close(ps["avg_word_len"], js_s["avg_word_len"]))
                self.assertEqual([list(h) for h in ps["hits"]], js_s["hits"])

    def test_model_probabilities(self):
        if self.model is None:
            self.skipTest("还没有 model.json")
        for text, js in zip(TEXTS, self.js):
            rule = tf.analyze(text, PHRASES)
            self.assertTrue(close(nm.probability(self.model["doc"]["rules"], nm.doc_values(rule)), js["prob"]))
            for s, p in zip(rule["sentence_details"], js["sentenceProbs"], strict=True):
                self.assertTrue(close(nm.probability(self.model["sentence"]["rules"], nm.sentence_values(s)), p))


if __name__ == "__main__":
    unittest.main()
